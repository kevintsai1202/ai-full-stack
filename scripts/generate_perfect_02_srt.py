def format_subtitle_text(text: str) -> str:
    """依標點符號規範：以半形空格取代逗號、句號、冒號、頓號等，句末不留標點或空格。"""
    t = text
    # 替換常見中文標點（逗號、句號、問號、驚嘆號、冒號、分號、頓號、括號、破折號）為半形空格
    t = re.sub(r"[，。！？：；（）()、—~～]", " ", t)
    # 壓縮多餘空格為單一空格
    t = re.sub(r" +", " ", t)
    return t.strip()

def main():
    bak_cues = load_bak()
    print(f"Loaded {len(bak_cues)} cues from 02.srt.bak")
    
    out_cues = []
    for idx, item in enumerate(MAPPING, start=1):
        b_st, b_en, text = item
        if isinstance(b_st, float):
            st = b_st
            en = b_en
        else:
            st = bak_cues[b_st - 1]["start"]
            en = bak_cues[b_en - 1]["end"]
            
        # 確保時長合理 (至少 1.0s)
        if en - st < 1.0:
            en = st + 1.0
            
        clean_txt = format_subtitle_text(text)
        out_cues.append({
            "idx": idx,
            "start": st,
            "end": en,
            "time_str": f"{fmt_time(st)} --> {fmt_time(en)}",
            "text": clean_txt
        })
        
    # 保證時間單調遞增且無重疊
    for i in range(1, len(out_cues)):
        if out_cues[i]["start"] < out_cues[i-1]["start"]:
            out_cues[i]["start"] = out_cues[i-1]["end"]
        if out_cues[i]["end"] <= out_cues[i]["start"]:
            out_cues[i]["end"] = out_cues[i]["start"] + 1.0
        out_cues[i]["time_str"] = f"{fmt_time(out_cues[i]['start'])} --> {fmt_time(out_cues[i]['end'])}"

    # 輸出 SRT
    lines = []
    for c in out_cues:
        lines.append(str(c["idx"]))
        lines.append(c["time_str"])
        lines.append(c["text"])
        lines.append("")
        
    out_path = ROOT / "course-package/ch01-env-and-ai-workflow/02.srt"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(out_cues)} perfect cues to {out_path}")

if __name__ == "__main__":
    main()
